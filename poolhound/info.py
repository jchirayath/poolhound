def masthead(public=True):
    """What this is, then the three things it does, under the wordmark.

    Both builds carry it, and it is the only statement of what this is that an
    anonymous visitor sees before they have scrolled anything. It used to be
    one sentence of three clauses joined with spaces -- every word of it true,
    and all of it answering "what does it do" to somebody who had not yet been
    told what it was, in a 1.55-line-height paragraph where three distinct
    promises read as one long qualification of each other.

    So the shape says what the content is: a sentence that names the category,
    and then the three AS THREE. Assembled from PURPOSE rather than typed, so
    it cannot come to describe a different product from the landing page
    directly below it -- which is a thing that has happened twice.

    This is the function name that used to be `tagline()`. It returns a block
    rather than a line now, and a name that has stopped being true is worse
    than no name.
    """
    does = "".join(
        f'<li>{icon(ic, 15)}<span>{html.escape(clause, quote=False)}</span></li>'
        for ic, _, clause, _ in PURPOSE)
    # WRAPPED, so the two can be laid out against each other. They were bare
    # siblings of the page wrapper, which meant the statement and the three
    # things it does could only ever stack — and on a 1140px page that left
    # the right-hand half of the first screen empty. One container is all the
    # stylesheet needs to put them side by side; see `.hero` in style.py.
    # THE HERO IS FOR A STRANGER, AND THE DASHBOARD IS NOT.
    #
    # The authenticated build opens on Home, which answers "how is the water
    # doing" to somebody who already knows what this is. A 44px statement of
    # the product's thesis above that pushes the first reading 400px down the
    # page to tell an operator something they came in knowing. The public
    # build has the opposite problem and is why the hero exists.
    #
    # So the same two pieces, two sizes: `.hero` on the public build, `.hero
    # compact` on the authenticated one, where the lead stands down to the
    # smallest text on the page and the three are hidden outright.
    cls = "hero" if public else "hero compact"
    return (f'<div class="{cls}">\n'
            f'<p class="tagline">{html.escape(WHAT_IT_IS, quote=False)}</p>\n'
            f'<ul class="does">{does}</ul>\n'
            f'</div>')


