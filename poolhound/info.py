# A purpose paragraph may credit a project by linking it, written
# [text](https://...). ESCAPED FIRST and linked after, so the only markup that
# can reach the page is an anchor this pattern built — never a tag that was in
# the text — and only to an https URL with no quote or space in it. The URL's
# host must be on the publishability roster like any other outbound link.
_LINK = re.compile(r"\[([^\]\[]+)\]\((https://[^\s()\"'<>]+)\)")


def _prose(text):
    return _LINK.sub(lambda m: f'<a href="{m.group(2)}" rel="noopener">'
                               f'{m.group(1)}</a>',
                     html.escape(text, quote=False))


def _fig(card, label, tab, alt, caption, public):
    """One screenshot, its name, and what it is a picture of."""
    from .help import _tablink
    name = _tablink(tab, label, public=public) if tab else html.escape(label)
    return f'''<figure class="shot">
  <img src="screenshots/{html.escape(card, quote=True)}" width="880" height="555"
       loading="lazy" decoding="async" alt="{html.escape(alt, quote=True)}">
  <figcaption><b>{name}</b> {html.escape(caption)}</figcaption>
</figure>'''


