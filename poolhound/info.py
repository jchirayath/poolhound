"""Poolhound info — the public landing page.

WHAT THIS TAB IS FOR

The public address is a public address, and what anonymous visitors used to
land on was Home: this household's current chlorine, its lab history, its
runtime. Nothing there was secret — Home is derived from the same measurements
the chemistry reference is — but it is a dashboard, and a dashboard answers
"how is it doing" to somebody who has not yet been told what "it" is. The first
screen a stranger sees should say what the thing does.

So Home moved behind the sign-in, where the people who own the pool are, and
this took its place.

THE PICTURES ARE OF A POOL THAT DOES NOT EXIST

Every screenshot on this page comes from `bin/demo-data` — a synthetic pool
built into a temporary directory by `bin/screenshots`, which asserts its own
isolation before it renders anything. That is deliberate and it is the whole
reason screenshots are allowed here at all: a live public dashboard would be
this household's readings, and a hand-cropped screenshot of the real one would
be the same thing with extra steps and no check. A generated picture of a
generated pool can be regenerated by anyone who clones this, and it cannot
leak, because there is nothing in it to leak.

The captions say so on the page as well. A reader who is not told a figure is
a demonstration will read it as live data, and this page's entire argument is
that a number should say where it came from.
"""

